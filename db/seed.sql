-- =====================================================================
-- ClaimFlow seed data: fictional insurer "Acme Cover". All people, emails
-- and numbers are invented. Dates are RELATIVE to the day the DB is created,
-- so the test scenarios behave the same whenever the project is set up.
--
-- Personal information (names, emails, phones) must be stored encrypted, but this
-- file can't encrypt: the key is generated per install and lives only in n8n.
-- So seed PI goes into the temporary table seed_pii. scripts/setup.sh encrypts it
-- into the *_enc / *_hmac columns with the same code the workflows use, then
-- DROPS seed_pii. See docs/security.md.
-- =====================================================================

CREATE TABLE seed_pii (
  policy_number text PRIMARY KEY REFERENCES policies (policy_number) DEFERRABLE INITIALLY DEFERRED,
  name          text NOT NULL,
  email         text NOT NULL,
  phone         text
);

